// Files that are text inside, or stored without compression: zipping makes them much smaller. Photos, videos,
// music, PDFs, Office files and archives are compressed already, so they are left alone.
const TYPES = [
  /^text\//,
  /^application\/(json|xml|javascript|ecmascript|x-ndjson|ld\+json|x-yaml|yaml|toml|sql|x-sh|x-tar|rtf)$/,
  /^image\/(svg\+xml|bmp|x-ms-bmp|tiff|x-icon|vnd\.microsoft\.icon)$/,
  /^audio\/(wav|x-wav|wave|aiff|x-aiff)$/,
];

// Browsers don't know a type for many text files, so then the name decides.
const EXTENSIONS = new Set([
  'txt',
  'md',
  'csv',
  'tsv',
  'json',
  'jsonl',
  'ndjson',
  'log',
  'xml',
  'svg',
  'html',
  'htm',
  'css',
  'js',
  'mjs',
  'cjs',
  'ts',
  'tsx',
  'jsx',
  'yml',
  'yaml',
  'toml',
  'ini',
  'cfg',
  'conf',
  'env',
  'sql',
  'sh',
  'bat',
  'ps1',
  'py',
  'rb',
  'go',
  'rs',
  'java',
  'kt',
  'c',
  'h',
  'cpp',
  'hpp',
  'cs',
  'php',
  'swift',
  'tex',
  'srt',
  'vtt',
  'ics',
  'vcf',
  'bmp',
  'tif',
  'tiff',
  'wav',
  'aif',
  'aiff',
  'tar',
]);

export const isCompressible = (file: File): boolean => TYPES.some(type => type.test(file.type))
  || EXTENSIONS.has(file.name.split('.').pop()?.toLowerCase() ?? '');
